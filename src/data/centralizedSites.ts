/**
 * LunarNavi - Centralized Candidate Landing Sites & Multi-Criteria Dataset
 *
 * Single centralized repository for all lunar south pole candidate locations.
 * Unifies authentic NASA Artemis III candidate regions, LOLA topography, Diviner thermal models,
 * LEND neutron spectroscopy, and LCROSS ground truth.
 *
 * Adheres strictly to the CandidateLocation, Site, and CriterionValue data contracts.
 * Unmeasured metrics are explicitly set to null with quality 'low' (never fabricated).
 */

import { Site } from '../engine/types'
import { CandidateLocation } from '../engine/locations'

export type SiteDesignation = 'official-artemis-candidate' | 'scientific-research-location'
export type ResourceEvidenceKind = 'direct-observation' | 'scientific-evidence' | 'proxy' | 'unknown'
export type QualityRating = 'high' | 'medium' | 'low'

export interface ExtractedMeasurement<T = number> {
  value: T | null
  unit: string
  dataset: string
  sourceUrl: string
  samplingMethod: string
  quality: QualityRating
  note?: string
}

export interface ResourceEvidence {
  kind: ResourceEvidenceKind
  score: number | null
  citation: string
  sourceUrl: string
  summary: string
  directObservation?: string
  thermalEvidence?: string
  neutronDeficitEvidence?: string
}

export interface CommunicationModel {
  assumedScenario: string
  directEarthVisibilityPercent: number | null
  relaySupported: boolean
  sourceUrl: string
  dataset: string
  modelNote: string
}

export interface CentralizedSite extends Site {
  designation: SiteDesignation
  sourceOrganization: string
  sourceUrl: string
  description: string
  coordinateConvention: string
  coordinateStatus: 'verified' | 'to-verify'
  measurements: {
    elevation: ExtractedMeasurement<number>
    slope: ExtractedMeasurement<number>
    roughness: ExtractedMeasurement<number>
    illumination: ExtractedMeasurement<number>
    isPsr: ExtractedMeasurement<boolean>
    psrDistanceKm: number
  }
  resourceEvidence: ResourceEvidence
  communicationModel: CommunicationModel
}

/**
 * Converts a CentralizedSite to the CandidateLocation interface for validation.
 */
export function toCandidateLocation(site: CentralizedSite): CandidateLocation {
  return {
    id: site.id,
    name: site.name,
    region: site.region,
    latitude: site.latitude,
    longitude: site.longitude,
    coordinateSource: `${site.sourceOrganization} (${site.designation === 'official-artemis-candidate' ? 'Official Artemis III Region' : 'Research Landmark'})`,
    sourceUrl: site.sourceUrl,
    coordinateConvention: site.coordinateConvention,
    status: site.coordinateStatus,
    note: site.description,
  }
}

