/**
 * Fast lookup map from site ID to CentralizedSite.
 */
export const SITE_MAP: Map<string, CentralizedSite> = new Map(
  CENTRALIZED_CANDIDATE_SITES.map((site) => [site.id, site])
)

/**
 * Retrieves a candidate site by unique ID.
 */
export function getSiteById(id: string): CentralizedSite | undefined {
  return SITE_MAP.get(id)
}

/**
 * Returns only the official NASA Artemis III candidate sites.
 */
export function getOfficialArtemisSites(): CentralizedSite[] {
  return CENTRALIZED_CANDIDATE_SITES.filter(
    (site) => site.designation === 'official-artemis-candidate'
  )
}

/**
 * Returns scientific research locations and ground-truth landmarks.
 */
export function getScientificResearchSites(): CentralizedSite[] {
  return CENTRALIZED_CANDIDATE_SITES.filter(
    (site) => site.designation === 'scientific-research-location'
  )
}

/**
 * Selects a decorrelated backup site for a given primary winner.
 * A good backup:
 * 1. Is feasible under the mission profile.
 * 2. Is in a distinct geological complex / crater from the primary site.
 * 3. Has high TOPSIS ranking among remaining sites.
 */
export function getDecorrelatedBackupSite(
  primarySiteId: string,
  rankedFeasibleSiteIds: string[]
): CentralizedSite | undefined {
  const primary = getSiteById(primarySiteId)
  if (!primary) return undefined

  for (const id of rankedFeasibleSiteIds) {
    if (id === primarySiteId) continue
    const candidate = getSiteById(id)
    if (!candidate) continue

    // Check decorrelation: different crater / complex
    if (candidate.region !== primary.region) {
      return candidate
    }
  }

  // If no different region, take the second highest ranking site
  const runnerUpId = rankedFeasibleSiteIds.find((id) => id !== primarySiteId)
  return runnerUpId ? getSiteById(runnerUpId) : undefined
}
